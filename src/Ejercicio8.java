

public class Ejercicio8 {

    /*
    Cree un programa que imprima los numeros entre 0 y 110 en orden ascendente y descendeste
     */

    public static void main(String[] args) {
        System.out.println("Ascendente:");
        for (int i = 0; i <= 100; i++) {
            System.out.print(i + " ");
        }
        System.out.println("\nDescendente:");
        for (int i = 100; i >= 0; i--) {
            System.out.print(i + " ");
        }

    }

}
